def main():
    raw = "\n".join(open(p, encoding="utf-8").read() for p in TEXT)
    txt = "\n".join(body(open(p, encoding="utf-8").read()) for p in TEXT)
    tokens = re.findall(r"\d+(?:\.\d+)?", txt)
    bad, rows = 0, []
    for printed, rule, spec, what in L1:
        if rule == "claim":
            continue
        ok, got = check(rule, spec, printed)
        rows.append({"printed": printed, "from": "w_checknums", "value_agrees": bool(ok), "appears": printed in tokens, "what": what})
        bad += not ok
    for printed, computed, what in w2.LEDGER:
        ok = printed == computed
        rows.append({"printed": printed, "from": "w2_checknums", "value_agrees": ok, "appears": printed in tokens, "what": what})
        bad += not ok
    crow = []
    for got, exp, rx in CLAIMS:
        ok, inn = got == exp, re.search(rx, raw, re.S) is not None
        crow.append({"pattern": rx, "computed": str(got), "expected": str(exp), "value_agrees": ok, "appears": inn})
        bad += not (ok and inn)
    covered = {r["printed"] for r in rows} | YEARS | STRUCTURAL
    unacc = sorted({t for t in tokens if t not in covered}, key=lambda t: (len(t), t))
    tables = subprocess.run([sys.executable, os.path.join(ROOT, "paper", "gen_tables.py"), "--check"],
                            capture_output=True, text=True)
    out = {"text_files": [os.path.relpath(p, ROOT) for p in TEXT], "ledger_entries": len(rows),
           "ledger_entries_used_in_text": sum(1 for r in rows if r["appears"]), "claims": len(CLAIMS),
           "failures": bad, "distinct_numeric_tokens": len(set(tokens)), "unaccounted_tokens": unacc,
           "generated_tables_unchanged": tables.returncode == 0, "tables_report": tables.stdout.strip().split("\n"),
           "rows": rows, "claim_rows": crow}
    out["all_pass"] = bad == 0 and not unacc and out["generated_tables_unchanged"]
    json.dump(out, open(os.path.join(J, "j_checknums.json"), "w"), indent=2)
    print(f"{len(rows)} ledger values re-evaluated ({out['ledger_entries_used_in_text']} used in the text), "
          f"{len(CLAIMS)} claims; {bad} failures; {len(set(tokens))} distinct numeric tokens, {len(unacc)} unaccounted; "
          f"tables unchanged: {out['generated_tables_unchanged']}")
    for r in rows:
        if not r["value_agrees"]:
            print("  FAIL", r)
    for r in crow:
        if not (r["value_agrees"] and r["appears"]):
            print("  FAIL", r)
    if unacc:
        print("  UNACCOUNTED", unacc)
    return 0 if out["all_pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
