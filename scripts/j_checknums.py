J = os.path.join(ROOT, "results", "json")
TEXT = [os.path.join(ROOT, "paper", f) for f in ("dam-abstract.tex", "dam-content.tex")]
YEARS = {"1956", "1971", "1979", "2002", "2015", "2017", "2019", "2026"}
