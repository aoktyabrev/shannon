"""Every number printed in the merged paper, reconciled by machine against results/json.

The paper is assembled from the two notes, so it is checked against the union of their
ledgers (scripts/w_checknums.py and scripts/w2_checknums.py, every entry of which is
re-evaluated here), plus claims written for this text.  Backward: every numeric token of
the text must be covered.  The two data tables are generated by paper/gen_tables.py; they
are checked by regenerating them and requiring the files to be unchanged.
"""
